const LangContext = createContext()

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(localStorage.getItem('alma_lang') || 'fr')

  // RTL support for Arabic (spec §17)
  useEffect(() => {
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
    document.documentElement.lang = lang
  }, [lang])

  const t = (k, vars) => {
    let s = dict[lang]?.[k] ?? dict.fr[k] ?? k
    if (vars) for (const [vk, vv] of Object.entries(vars)) s = s.replaceAll(`{${vk}}`, vv)
    return s
  }
  const setLang = (l) => { localStorage.setItem('alma_lang', l); setLangState(l) }

  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>
}

export const useLang = () => useContext(LangContext)

