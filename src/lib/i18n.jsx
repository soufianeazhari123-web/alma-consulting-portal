const LangContext = createContext()

export function LangProvider({ children }) {
  const [lang, setLang] = useState(localStorage.getItem('alma_lang') || 'fr')
  const t = (k) => dict[lang]?.[k] ?? dict.fr[k] ?? k
  const set = (l) => { localStorage.setItem('alma_lang', l); setLang(l) }
  return <LangContext.Provider value={{ lang, setLang: set, t }}>{children}</LangContext.Provider>
}

export const useLang = () => useContext(LangContext)
